CREATE TABLE FACE_BIOMETRIC_PROFILE (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    USER_ID VARCHAR2(128) NOT NULL,
    MODEL_ID VARCHAR2(128) NOT NULL,
    MODEL_VERSION VARCHAR2(64) NOT NULL,
    EMBEDDING_DIMENSION NUMBER(10) NOT NULL,
    EMBEDDING_DATA BLOB NOT NULL,
    NORMALIZED NUMBER(1) DEFAULT 1 NOT NULL,
    STATUS VARCHAR2(32) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_FACE_BIOMETRIC_PROFILE PRIMARY KEY (ID),
    CONSTRAINT UK_FACE_BIOMETRIC_USER_MODEL UNIQUE (USER_ID, MODEL_ID, MODEL_VERSION),
    CONSTRAINT CK_FACE_BIOMETRIC_DIM CHECK (EMBEDDING_DIMENSION = 512),
    CONSTRAINT CK_FACE_BIOMETRIC_NORMALIZED CHECK (NORMALIZED IN (0,1))
);

CREATE INDEX IX_FACE_BIOMETRIC_USER ON FACE_BIOMETRIC_PROFILE(USER_ID);
